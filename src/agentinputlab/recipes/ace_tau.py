SCHEMA = "agentinputlab.ace.Tau.native_feedback_input.v1"
PLAN_INSTRUCTION = (
    "Solve the supplied task as one noninteractive tool plan. Preserve all visible task "
    "rules and function schemas. Put exactly one JSON object in your final_answer string: "
    '{"actions":[{"name":"visible_function_name","arguments":{}}],"response":"message to user"}. '
    "Use only advertised tools with their required arguments. Actions execute in order without "
    "another model call, access to tool replies while planning, or another user turn. The response "
    "ends this declared plan. Do not output Python, code fences, placeholder variables or extra fields.\n"
)


def _provider(domain):
    if domain == "retail":
        from workers.official_arenas.providers.tau_retail import TauRetailProvider

        return TauRetailProvider()
    if domain == "banking_knowledge":
        from workers.official_arenas.providers.tau3 import Tau3Provider

        return Tau3Provider()
    raise ValidationError("ACE Tau supports explicit retail or banking_knowledge domains")


def _same_backbone(configuration, target):
    model = target.get("model_id") if isinstance(target, Mapping) else None
    agent = configuration.get("llm_agent")
    if (
        not isinstance(model, str)
        or not model
        or not isinstance(agent, str)
        or agent not in (model, "openai/" + model)
        or configuration.get("llm_user") != agent
        or configuration.get("llm_judge", agent) != agent
    ):
        raise ValidationError("ACE Tau user and judge must follow the declared target backbone")
    seed = configuration.get("llm_args_agent", {}).get("seed")
    if type(seed) is not int:
        raise ValidationError("ACE Tau needs an explicit integer evaluated-agent seed")


def _native_inputs(checkout, domain, rows, provider):
    from tau2.data_model.message import AssistantMessage, ToolMessage, UserMessage
    from tau2.data_model.tasks import InitialState
    from tau2.runner.build import _build_env_kwargs, build_environment
    from tau2.runner.helpers import get_tasks, load_task_splits
    from tau2.utils.utils import DATA_DIR

    if Path(DATA_DIR).resolve() != checkout / "data":
        raise ExternalDependencyError("ACE Tau data must belong to the verified native checkout")
    split = load_task_splits(domain)
    if domain == "retail":
        if not isinstance(split, dict) or not {"train", "test"} <= split.keys():
            raise ValidationError("Retail official task split is unavailable")
        train = set(map(str, split["train"]))
        if train & set(map(str, split["test"])):
            raise ValidationError("Retail native training and test splits overlap")
    elif split is not None:
        raise ValidationError("Banking split semantics changed; re-declare the fitting protocol")
    tasks, histories, schemas, kwargs, configs = {}, {}, {}, {}, {}
    kinds = {"assistant": AssistantMessage, "tool": ToolMessage, "user": UserMessage}
    for row in rows:
        key = row["case_id"]
        cfg = provider._validate_config(row["native_configuration"])
        state = _state(row["state"])
        protected = row["protected_checkpoint"]["protected"]
        if (
            cfg["task_set_name"] != domain
            or cfg["task_split_name"] != "train"
            or (domain == "retail" and key not in train)
            or protected["task_id"] != key
            or state.task_id != key
            or protected["locked_dependency_hashes"] != cfg["locked_dependency_hashes"]
        ):
            raise ValidationError("Tau task, training origin or dependency binding differs")
        matches = get_tasks(domain, task_split_name=cfg["task_split_name"], task_ids=[key])
        if len(matches) != 1 or str(matches[0].id) != key:
            raise ValidationError("Tau fitting task is missing from the native inventory")
        task = matches[0]
        history = [kinds[m["role"]].model_validate(m) for m in protected["initial_message_history"]]
        if (
            not history
            or not isinstance(history[-1], UserMessage)
            or history[-1].is_tool_call()
            or state.query != history[-1].content
        ):
            raise ValidationError("Tau feedback requires its frozen initial visible user message")
        initial = task.initial_state
        task = task.model_copy(
            update=dict(
                initial_state=InitialState(
                    initialization_data=initial.initialization_data if initial else None,
                    initialization_actions=initial.initialization_actions if initial else None,
                    message_history=copy.deepcopy(history),
                )
            ),
            deep=True,
        )
        env_args = _build_env_kwargs(
            provider._run_config(cfg, budget=to_jsonable(state.budget)), task
        )
        environment = build_environment(domain, env_kwargs=env_args)
        tool_schema = [to_jsonable(t.openai_schema) for t in environment.get_tools()]
        names = {t.get("name") or t.get("function", {}).get("name") for t in tool_schema}
        if (
            not names
            or names != set(state.tool_names)
            or state.instruction != environment.get_policy()
        ):
            raise ValidationError("Tau visible native policy or tool inventory differs")
        catalogs = [c for c in state.context if c.block_id == "official_tool_catalog"]
        if len(catalogs) != 1:
            raise ValidationError("Tau frozen visible state needs its native tool catalog")
        import json

        if to_jsonable(json.loads(catalogs[0].text)) != tool_schema:
            raise ValidationError("Tau frozen function schemas differ from the native environment")
        tasks[key], histories[key], schemas[key] = task, history, tool_schema
        configs[key], kwargs[key] = cfg, env_args
    files = list((checkout / "src/tau2").rglob("*.py"))
    data = checkout / "data/tau2/domains" / domain
    if domain == "retail":
        files.extend(
            data / name for name in ("db.json", "policy.md", "tasks.json", "split_tasks.json")
        )
    else:
        files.append(data / "db.json")
        files.extend(p for p in (data / "documents").rglob("*") if p.is_file())
        files.extend(data / "tasks" / (key + ".json") for key in tasks)
    return tasks, histories, schemas, kwargs, configs, source_file_pins(checkout, files)


def build_ace_tau_feedback_input(
    *,
    checkout,
    domain: str,
    captures: Sequence[Mapping],
    native_configurations: Mapping,
    train_ids: Sequence[str],
    validation_ids: Sequence[str],
    heldout_ids: Sequence[str],
    partition_label: str,
    target_model: Mapping,
    output_path,
):
    """Prepare existing captures, without user/agent/judge model calls."""
    provider = _provider(domain)
    root = verify_native_checkout(checkout, revision=provider.source_revision)
    ids = [*train_ids, *validation_ids]
    if (
        not train_ids
        or not validation_ids
        or any(not isinstance(k, str) or not k for k in ids)
        or len(ids) != len(set(ids))
        or set(ids) & set(heldout_ids)
        or not isinstance(partition_label, str)
        or not partition_label.strip()
        or not isinstance(native_configurations, Mapping)
        or set(ids) != set(native_configurations)
    ):
        raise ValidationError(
            "Tau needs disjoint fitting groups, per-case configurations and a label"
        )
    selected = [c for c in captures if c["checkpoint_id"] in ids]
    if len(selected) != len(ids) or {c["checkpoint_id"] for c in selected} != set(ids):
        raise ValidationError("Tau capture IDs are missing or duplicated")
    by_id = {c["checkpoint_id"]: to_jsonable(c) for c in selected}
    rows = []
    for role, group in (("train", train_ids), ("validation", validation_ids)):
        for key in group:
            cfg = to_jsonable(native_configurations[key])
            _same_backbone(cfg, target_model)
            state = _state(by_id[key]["visible_state"])
            rows.append(
                dict(
                    case_id=key,
                    role=role,
                    state=to_jsonable(state),
                    state_hash=state.state_hash,
                    protected_checkpoint=by_id[key],
                    native_configuration=cfg,
                )
            )
    with native_process_scope(root, package="tau2"):
        _, _, schemas, _, _, pins = _native_inputs(root, domain, rows, provider)
    value = dict(
        schema=SCHEMA,
        benchmark=provider.benchmark_id,
        domain=domain,
        native_source_revision=provider.source_revision,
        source_files=pins,
        fitting_rows=rows,
        heldout_ids=list(heldout_ids),
        source_official_split="train" if domain == "retail" else None,
        partition_source=partition_label,
        target_model=to_jsonable(target_model),
        environment_model=to_jsonable(target_model),
        native_function_schemas=schemas,
        initial_user_captures_reused_NOT_regenerated=True,
        builder_model_calls=0,
        ToolTalk_not_used=True,
    )
    path = Path(output_path).expanduser().absolute()
    if path.resolve().is_relative_to(root) or path.exists() or path.is_symlink():
        raise ValidationError("Tau input must be a new file outside the clean native checkout")
    _save(path, value)
    return dict(path=str(path), sha256=_sha(path))


class ACETauFeedback(NativePlanFeedback):
    """Native Tau reward for a frozen, explicitly noninteractive tool plan."""

    processor_id = "agentinputlab.ace.Tau.native_tool_plan_feedback.v1"
    metric = "official_reward"

    def __init__(
        self, *, checkout, source_input, output_root, mode="offline", environment_base_url=None
    ):
        self._initialize(
            checkout=checkout, source_input=source_input, output_root=output_root, mode=mode
        )
        self.domain = self.source.get("domain")
        self.provider = _provider(self.domain)
        if (
            self.source.get("schema") != SCHEMA
            or self.source.get("benchmark") != self.provider.benchmark_id
        ):
            raise ValidationError("Tau feedback schema or benchmark differs")
        self.checkout = verify_native_checkout(checkout, revision=self.provider.source_revision)
        self._verify_source()
        expected_split = "train" if self.domain == "retail" else None
        if self.source["source_official_split"] != expected_split or not self.source.get(
            "partition_source"
        ):
            raise ValidationError("Tau official/caller-defined split provenance differs")
        for row in self.rows.values():
            _same_backbone(row["native_configuration"], self.source["target_model"])
        if self.source["target_model"] != self.source["environment_model"]:
            raise ValidationError("Tau environment and target backbone bindings differ")
        with native_process_scope(self.checkout, package="tau2"):
            self.tasks, self.histories, self.schemas, self.env_kwargs, self.configs, pins = (
                _native_inputs(self.checkout, self.domain, list(self.rows.values()), self.provider)
            )
        if (
            pins != self.source["source_files"]
            or self.schemas != self.source["native_function_schemas"]
        ):
            raise ValidationError("Tau native source or visible function schemas changed")
        self.environment_base_url = environment_base_url
        if environment_base_url is not None:
            url = urlsplit(environment_base_url) if isinstance(environment_base_url, str) else None
            if (
                not url
                or url.scheme not in ("http", "https")
                or not url.hostname
                or url.username
                or url.password
            ):
                raise ValidationError(
                    "Tau environment endpoint must be an explicit credential-free HTTP URL"
                )
        self.tool_names = {k: set(s.tool_names) for k, s in self.states.items()}
        self._create_output()

    def fingerprint(self):
        self._verify_source()
        return dict(
            processor_id=self.processor_id,
            mode=self.mode,
            source_input=self.source_input,
            source_files=self.source["source_files"],
            source_revision=self.provider.source_revision,
            scorer_id=self.provider.scorer_id,
            scorer_revision=self.provider.scorer_revision,
            provider_source_sha256=_sha(inspect.getfile(type(self.provider))),
            task_adapter_source_sha256=_sha(__file__),
            target_model=self.source["target_model"],
            environment_model=self.source["environment_model"],
            environment_base_url=self.environment_base_url,
            source_official_split=self.source["source_official_split"],
            partition_source=self.source["partition_source"],
            groups={
                role: [
                    dict(case_id=k, state_hash=r["state_hash"])
                    for k, r in self.rows.items()
                    if r["role"] == role
                ]
                for role in ("train", "validation")
            },
            visible_tool_schemas_sha256={k: content_hash(v) for k, v in self.schemas.items()},
            feedback_metric=self.metric,
            initial_user_captures_reused_NOT_regenerated=True,
            noninteractive_plan_NOT_native_closed_loop_agent=True,
            heldout_feedback_NOT_used=True,
            transductive_NOT_independent_heldout=self.mode == "online",
            ToolTalk_NOT_used=True,
            native_user_simulator_calls=0,
            native_judge_controls_and_costs_separate=True,
            automatic_retry=False,
        )

    def _example(self, key, split):
        state = self.states[key]
        visible = dict(
            query=state.query,
            instruction=state.instruction,
            messages=state.messages,
            context=state.context,
            tool_names=state.tool_names,
            native_function_tools=self.schemas[key],
        )
        return ACEExample(
            example_id=key,
            input=dict(question=PLAN_INSTRUCTION + canonical_json(visible)),
            expected_output=key,
            split=split,
            metadata=dict(
                source_state_hash=state.state_hash,
                task_processor=self.processor_id,
                evaluator_target_is_opaque_case_id=True,
            ),
        )

    def _native_score(self, key, plan, folder):
        with native_process_scope(self.checkout, package="tau2"):
            from tau2.data_model.message import AssistantMessage, ToolCall
            from tau2.data_model.simulation import SimulationRun, TerminationReason
            from tau2.evaluator import evaluator_nl_assertions
            from tau2.evaluator.evaluator import EvaluationType, evaluate_simulation
            from tau2.runner.build import build_environment
            from tau2.utils import llm_utils

            from workers.official_arenas.providers import tau3, tau_retail

            started, start_time = time.monotonic(), datetime.now(timezone.utc).isoformat()
            task, cfg = self.tasks[key], copy.deepcopy(self.configs[key])
            history = copy.deepcopy(self.histories[key])
            if self.environment_base_url is not None:
                for role in ("agent", "user", "judge"):
                    if "llm_args_" + role in cfg:
                        cfg["llm_args_" + role]["api_base"] = self.environment_base_url
            original_cost = llm_utils.get_response_cost
            original_judge = (
                evaluator_nl_assertions.DEFAULT_LLM_NL_ASSERTIONS,
                evaluator_nl_assertions.DEFAULT_LLM_NL_ASSERTIONS_ARGS,
            )
            try:
                tau3._install_local_tau_cost_accounting(cfg)
                if self.domain == "banking_knowledge":
                    tau3._install_local_tau_nl_evaluator(cfg)
                environment = build_environment(self.domain, env_kwargs=self.env_kwargs[key])
                initial = task.initial_state
                environment.set_state(
                    initial.initialization_data,
                    initial.initialization_actions,
                    copy.deepcopy(history),
                    strict=True,
                )
                for index, action in enumerate(plan["actions"]):
                    call = ToolCall(
                        id="ace_plan_" + str(index),
                        name=action["name"],
                        arguments=action["arguments"],
                        requestor="assistant",
                    )
                    history.append(AssistantMessage.text("", tool_calls=[call]))
                    history.append(environment.get_response(call))
                history.append(AssistantMessage.text(plan["response"]))
                simulation = SimulationRun(
                    id="ace-fitting-" + key,
                    task_id=key,
                    start_time=start_time,
                    end_time=datetime.now(timezone.utc).isoformat(),
                    duration=time.monotonic() - started,
                    termination_reason=TerminationReason.AGENT_STOP,
                    seed=cfg["llm_args_agent"]["seed"],
                    messages=history,
                    agent_cost=0.0,
                    user_cost=0.0,
                )
                _save(
                    folder / "before-native-scorer.json",
                    dict(
                        case_id=key,
                        plan=plan,
                        messages=[m.model_dump(mode="json") for m in history],
                        source_state_hash=self.states[key].state_hash,
                        native_noninteractive_plan_NOT_interactive_rollout=True,
                        evaluated_agent_model_calls=0,
                        native_user_simulator_calls=0,
                    ),
                )
                context = (
                    tau_retail.bound_retail_judge(
                        cfg, list(task.evaluation_criteria.nl_assertions or [])
                    )
                    if self.domain == "retail"
                    else nullcontext()
                )
                with context:
                    reward = evaluate_simulation(
                        simulation,
                        task,
                        evaluation_type=EvaluationType.ALL,
                        solo_mode=False,
                        domain=self.domain,
                        env_kwargs=self.env_kwargs[key],
                        strict_replay=True,
                    )
            finally:
                llm_utils.get_response_cost = original_cost
                (
                    evaluator_nl_assertions.DEFAULT_LLM_NL_ASSERTIONS,
                    evaluator_nl_assertions.DEFAULT_LLM_NL_ASSERTIONS_ARGS,
                ) = original_judge
            result = dict(
                status="native_Tau_noninteractive_tool_plan_scored",
                case_id=key,
                native_metrics=dict(official_reward=float(reward.reward)),
                native_reward_info=reward.model_dump(mode="json"),
                ordered_action_count=len(plan["actions"]),
                source_state_hash=self.states[key].state_hash,
                evaluated_agent_model_calls=0,
                native_user_simulator_calls=0,
                noninteractive_plan_agent_stop_explicit_NOT_native_interactive_success_claim=True,
            )
            _save(folder / "native-score.json", result)
            return result


def create_tau_feedback(**configuration):
    """Flat-JSON startup factory for the isolated native ACE worker."""
    return ACETauFeedback(**configuration)
