#!/usr/bin/env python3
"""Durable, first-attempt-only Retail atomic worker.

The original generic worker and historical providers are unchanged. This
worker reuses their request/budget validators but never uses TemporaryDirectory.
An operator must bind an immutable scope after verifying the actual human
scope/environment choices; hash-shaped authorization references alone are not
proof of consent. No enabled real scope is generated by this module.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from workers.official_arenas import driver as shared
from workers.official_arenas.protocol import (
    OfficialArenaError, content_hash, intervention_usage, materialized_state,
    merge_usage, resolve_shared_budget_config, sha256_file,
)
from workers.official_arenas.providers.tau_retail import SOURCE_REVISION, _create_only

SCOPE_PATH_ENV = "AILAB_RETAIL_EXECUTION_SCOPE"
SCOPE_SHA256_ENV = "AILAB_RETAIL_EXECUTION_SCOPE_SHA256"
SCOPE_PROTOCOL = "agentinputlab.retail-execution-scope.v1"
PROVIDER_ENTRYPOINT = "workers.official_arenas.providers.tau_retail:factory"
_SHA = re.compile(r"^[0-9a-f]{64}$")
_SCOPE_FIELDS = frozenset({"schema_version", "protocol", "source_revision", "phase", "execution_enabled",
    "output_root", "provider_config_sha256", "provider_source_sha256", "worker_support_sha256",
    "worker_source_sha256", "protocol_source_sha256", "provider_helper_sha256",
    "authorizations", "allowed_cell_ids"})


class RetailAttemptUnavailable(OfficialArenaError):
    """Existing live/interrupted/unscored attempt must be inspected, not rerun."""


def _reject_duplicate_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise OfficialArenaError("Retail JSON has duplicate fields")
        result[key] = value
    return result


def _read(path: Path) -> Mapping[str, Any]:
    if path.is_symlink() or not path.is_file():
        raise OfficialArenaError("Retail bound file is absent or symlinked")
    try:
        value = json.loads(path.read_bytes(), object_pairs_hook=_reject_duplicate_keys)
        content_hash(value)  # also rejects non-finite numbers
    except (ValueError, TypeError) as error:
        raise OfficialArenaError("Retail bound file is invalid JSON") from error
    if not isinstance(value, Mapping):
        raise OfficialArenaError("Retail bound file must be an object")
    return value


def cell_identity(request: Mapping[str, Any]) -> Mapping[str, Any]:
    """Logical cell identity excludes generated text, not method/budget/locks.

    If a generated payload changes, its logical identity stays occupied and
    its full request hash conflicts instead of silently becoming a new trial.
    Different factors/intensities require their own frozen arm parameters.
    """
    arms = []
    for arm in sorted(request["arms"], key=lambda item: item["role"]):
        payload = arm["payload"]
        arms.append({"role": arm["role"], "arm_id": arm["arm_id"],
                     **{name: payload[name] for name in ("release_id", "profile_kind", "model_slot", "arm_parameters")},
                     "budget": materialized_state(payload)["budget"]})
    return {**{name: request[name] for name in ("benchmark_id", "checkpoint_id", "source_revision",
                "origin_state_hash", "replay_identity", "seed", "locked_dependency_hashes")}, "arms": arms}


def _validate_authorizations(approvals: Any) -> None:
    # These are provenance references, not automatic verification of consent.
    # The operator must verify the actual human messages before enabling a scope.
    if not isinstance(approvals, Mapping) or set(approvals) != {"scope", "environment_models"}:
        raise OfficialArenaError("Retail human choice references are incomplete")
    for approval in approvals.values():
        if (not isinstance(approval, Mapping) or set(approval) != {"source_kind", "thread_id", "message_sha256"}
                or approval["source_kind"] != "human_message" or not isinstance(approval["thread_id"], str)
                or not approval["thread_id"].strip() or not isinstance(approval["message_sha256"], str)
                or _SHA.fullmatch(approval["message_sha256"]) is None):
            raise OfficialArenaError("Retail human choice reference is invalid")


def _scope(parameters: Mapping[str, Any], request: Mapping[str, Any]):
    path_text, expected = os.environ.get(SCOPE_PATH_ENV), os.environ.get(SCOPE_SHA256_ENV)
    if not path_text or not expected or _SHA.fullmatch(expected) is None:
        raise OfficialArenaError("Retail requires an explicitly bound execution scope")
    path = Path(path_text)
    value = _read(path)
    if sha256_file(path) != expected or set(value) != _SCOPE_FIELDS:
        raise OfficialArenaError("Retail execution scope differs")
    if (type(value["schema_version"]) is not int or value["schema_version"] != 1
            or value["protocol"] != SCOPE_PROTOCOL or value["source_revision"] != SOURCE_REVISION
            or value["phase"] not in {"engineering", "formal"} or value["execution_enabled"] is not True):
        raise OfficialArenaError("Retail execution scope is not enabled or valid")
    _validate_authorizations(value["authorizations"])
    files = {"provider_source_sha256": Path(__file__).parent / "providers/tau_retail.py",
             "worker_support_sha256": Path(shared.__file__), "worker_source_sha256": Path(__file__),
             "protocol_source_sha256": Path(__file__).parent / "protocol.py",
             "provider_helper_sha256": Path(__file__).parent / "providers/tau3.py"}
    for name, source in files.items():
        if source.is_symlink() or value[name] != sha256_file(source):
            raise OfficialArenaError("Retail worker source closure differs")
    config_hash = content_hash(resolve_shared_budget_config(parameters["provider_config"]))
    if value["provider_config_sha256"] != config_hash:
        raise OfficialArenaError("Retail frozen provider config differs")
    allowed = value["allowed_cell_ids"]
    if (not isinstance(allowed, list) or not allowed
            or any(not isinstance(item, str) or _SHA.fullmatch(item) is None for item in allowed)
            or len(allowed) != len(set(allowed))):
        raise OfficialArenaError("Retail frozen cell inventory is invalid")
    identity = cell_identity(request)
    cell_id = content_hash(identity)
    if cell_id not in allowed:
        raise OfficialArenaError("Retail cell is outside its approved frozen inventory")
    root = Path(value["output_root"])
    if (not root.is_absolute() or any(part.is_symlink() for part in (root, *root.parents))
            or not root.is_dir() or root.stat().st_uid != os.getuid() or root.stat().st_mode & 0o077):
        raise OfficialArenaError("Retail ledger root must be an existing owned private directory")
    return value, expected, root / cell_id, identity


def _sealed(value: Mapping[str, Any]) -> dict[str, Any]:
    return {**value, "receipt_sha256": content_hash(value)}


def _files(root: Path) -> dict[str, str]:
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise OfficialArenaError("Retail attempt contains a symlink")
        if path.is_file() and path != root / "terminal.json":
            result[str(path.relative_to(root))] = sha256_file(path)
    return result


def _cached(root: Path, request_hash: str, scope_sha256: str):
    if root.is_symlink() or not root.is_dir():
        raise OfficialArenaError("Retail logical attempt directory is invalid")
    start = _read(root / "pair-start.json")
    if start.get("request_hash") != request_hash or start.get("scope_sha256") != scope_sha256:
        raise OfficialArenaError("Retail existing logical cell has a different full request or scope")
    if not (root / "terminal.json").exists():
        raise RetailAttemptUnavailable("Retail attempt is live or interrupted; automatic retry is forbidden")
    terminal = _read(root / "terminal.json")
    body = {key: value for key, value in terminal.items() if key != "receipt_sha256"}
    if (terminal.get("receipt_sha256") != content_hash(body) or terminal.get("request_hash") != request_hash
            or terminal.get("scope_sha256") != scope_sha256 or terminal.get("files") != _files(root)):
        raise OfficialArenaError("Retail terminal or raw trajectory evidence differs")
    if terminal.get("status") != "paired_scored":
        raise RetailAttemptUnavailable("Retail failed attempt is retained and terminal; automatic retry is forbidden")
    response = _read(root / "response.json")
    if content_hash(response) != terminal.get("response_sha256"):
        raise OfficialArenaError("Retail retained response differs")
    return response


def run(value: Any) -> Mapping[str, Any]:
    if not isinstance(value, Mapping) or set(value) != shared._ROOT_FIELDS:
        raise OfficialArenaError("Retail atomic envelope fields differ")
    if type(value["schema_version"]) is not int or value["schema_version"] != 1 or value["protocol"] != shared.REQUEST_PROTOCOL:
        raise OfficialArenaError("Retail atomic envelope protocol differs")
    base = {name: value[name] for name in shared._ROOT_FIELDS - {"request_hash"}}
    if value["request_hash"] != content_hash(base):
        raise OfficialArenaError("Retail full request hash differs")
    parameters, request = shared._parameters(value["worker_parameters"]), shared._atomic_request(value["atomic_request"])
    if (parameters["provider_entrypoint"] != PROVIDER_ENTRYPOINT or request["benchmark_id"] != "tau3.retail"
            or request["source_revision"] != SOURCE_REVISION or request["seed"] != 17):
        raise OfficialArenaError("Retail cannot run another provider, domain, source or seed")
    records = shared._inventory(parameters)
    replay = records.get(request["checkpoint_id"])
    if (records["__inventory__"] != {"benchmark_id": "tau3.retail", "source_revision": SOURCE_REVISION}
            or replay is None or any(replay[name] != request[name] for name in ("origin_state_hash", "replay_identity"))):
        raise OfficialArenaError("Retail protected replay identity differs")
    shared._validate_dependency_binding(request=request, parameters=parameters, replay_record=replay)
    _, scope_sha, root, identity = _scope(parameters, request)
    provider = shared._provider(PROVIDER_ENTRYPOINT)
    if (provider.benchmark_id != request["benchmark_id"] or provider.source_revision != SOURCE_REVISION
            or provider.scorer_id != parameters["scorer_id"] or provider.scorer_revision != parameters["scorer_revision"]):
        raise OfficialArenaError("Retail provider identity differs from the worker lock")
    blockers = provider.doctor(parameters["provider_config"])
    if blockers:
        raise OfficialArenaError("Retail native preflight did not pass")
    try:
        root.mkdir(mode=0o700)
    except FileExistsError:
        return _cached(root, value["request_hash"], scope_sha)
    _create_only(root / "pair-start.json", {"request_hash": value["request_hash"], "scope_sha256": scope_sha,
        "cell_identity": identity, "pid": os.getpid(), "uid": os.getuid(), "retry_permitted": False})
    _create_only(root / "request.json", value)
    results, receipts, failures, runtime_ids = [], [], [], set()
    for arm in sorted(request["arms"], key=lambda item: item["role"]):
        role, work = arm["role"], root / arm["role"]
        work.mkdir(mode=0o700)
        try:
            result = provider.run_arm(parameters["provider_config"], replay_record=replay,
                arm_payload=arm["payload"], seed=17, role=role, work_dir=work)
            # Preserve raw evidence even if the following budget/runtime audit fails.
            _create_only(work / "trace.json", dict(result.trace))
            if result.runtime_instance_id in runtime_ids:
                raise OfficialArenaError("Retail paired arms reused one native runtime")
            runtime_ids.add(result.runtime_instance_id)
            usage = merge_usage(intervention_usage(arm["payload"]), result.usage)
            shared._validate_shared_budget_usage(arm["payload"], usage)
            # The host process bridge accepts exactly these five public fields.
            # Additional diagnostics belong in retained private arm evidence,
            # not in a response that the bridge will reject as schema drift.
            row = {"role": role, "arm_id": arm["arm_id"], "metrics": dict(result.metrics),
                   "trace_hash": content_hash(result.trace),
                   "usage": {name: usage[name] for name in shared._USAGE_FIELDS}}
            results.append(row)
            receipts.append({"role": role, "arm_id": arm["arm_id"], "origin_state_hash": request["origin_state_hash"],
                "replay_identity": request["replay_identity"], "seed": 17, "locked_dependency_hashes": request["locked_dependency_hashes"],
                "runtime_instance_id": result.runtime_instance_id, "completed": True})
            outcome = {"status": "scored_terminal", "result": row,
                       "trace_measurement": shared._safe_trace_measurement(result.trace),
                       "intervention_failure": shared._intervention_failure(arm["payload"])}
        except Exception as error:
            outcome = {"status": "failed_unscored", "exception_type": type(error).__name__,
                       "exception_sha256": hashlib.sha256(str(error).encode()).hexdigest(),
                       "retry_permitted": False, "paper_endpoint": None}
            failures.append(role)
        _create_only(work / "arm-outcome.json", _sealed(outcome))
    response = None
    if not failures:
        receipt = {**{name: request[name] for name in ("benchmark_id", "checkpoint_id", "source_revision",
            "origin_state_hash", "replay_identity", "seed", "locked_dependency_hashes")},
            **{name: parameters[name] for name in ("bridge_id", "bridge_revision", "scorer_id", "scorer_revision")}, "arms": receipts}
        response = {"schema_version": 1, "protocol": shared.RESPONSE_PROTOCOL,
                    "request_hash": value["request_hash"], "receipt": receipt, "arms": results}
        _create_only(root / "response.json", response)
    terminal = {"protocol": "retail-pair-terminal.v1", "request_hash": value["request_hash"], "scope_sha256": scope_sha,
        "status": "failed_unscored" if failures else "paired_scored", "failed_roles": failures,
        "physical_arm_attempts": 2, "retry_permitted": False, "files": _files(root),
        "response_sha256": content_hash(response) if response else None}
    _create_only(root / "terminal.json", _sealed(terminal))
    if failures:
        raise RetailAttemptUnavailable("Retail arm failure retained; both arms have dispositions, no retry")
    return response


def main() -> int:
    parser = argparse.ArgumentParser(description="Execute one frozen Retail pair, retaining first attempts")
    parser.add_argument("--doctor", action="store_true")
    args = parser.parse_args()
    if args.doctor:
        print(json.dumps({"protocol": shared.WORKER_PROTOCOL, "worker_available": True,
                          "scientific_ready": False, "requires_bound_execution_scope": True}))
        return 0
    try:
        response = run(json.load(sys.stdin, object_pairs_hook=_reject_duplicate_keys))
    except Exception as error:
        print(json.dumps({"error": type(error).__name__, "message": "Retail rejected or retained an unscored attempt; inspect owned ledger"}), file=sys.stderr)
        return 2
    print(json.dumps(response, sort_keys=True, ensure_ascii=False, allow_nan=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
